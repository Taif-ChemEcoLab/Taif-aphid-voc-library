def test_published_confidence_codes_preserved_with_descriptive_derivatives():
    source = pd.read_csv(ROOT / "data/v1/v1_published_features.csv", dtype=str, keep_default_na=False)
    assert "published_confidence_notation" not in source.columns
    assert "identification_confidence" not in source.columns
    expected = {"*": 11, "?": 32, "??": 27, "UK": 11}
    assert source["confidence_symbol"].value_counts().to_dict() == expected
    assert PUBLISHED_FEATURES["confidence_symbol"].value_counts().to_dict() == expected
    assert PUBLISHED_FEATURES["published_confidence_notation"].equals(PUBLISHED_FEATURES["confidence_symbol"])
    assert PUBLISHED_FEATURES["identification_confidence"].notna().all()
    assert set(PUBLISHED_FEATURES["identification_confidence"]) == set(CONFIDENCE_LABELS.values())
    exported = feature_catalog().to_csv(index=False)
    assert "published_confidence_notation" in exported.splitlines()[0]
    assert "identification_confidence" in exported.splitlines()[0]


def test_assistant_uses_descriptive_confidence_terminology():
    answer = answer_question("What do the identification-confidence categories mean?")
    assert "11 Authentic-standard supported" in answer.answer
    assert "32 Tentative identification, higher library match" in answer.answer
    assert "27 Tentative identification, lower library match" in answer.answer
    assert "11 Unknown features" in answer.answer
    assert "not generated by VOC·BIO" in answer.answer
    assert "confirmed chemical identities" in answer.caution
    assert {"published_confidence_notation", "identification_confidence"}.issubset(answer.records.columns)


def test_exact_headline_values_and_correlation():
    pairs = fd.pair_results()
    grouped = pairs.groupby("receptor_name")["median_rank1_score"]
    assert np.isclose(grouped.median()["MvicOBP3"], -4.712, atol=1e-12)
    assert np.isclose(grouped.median()["NribOBP3"], -4.7895, atol=1e-12)
    comparison = fd.table("comparison")
    assert np.isclose(comparison[["MvicOBP3", "NribOBP3"]].corr().iloc[0, 1], 0.9600100221, atol=1e-10)
    bio39 = comparison.set_index("bio_id").loc["Bio39"]
    assert np.isclose(bio39["Mvic_minus_Nrib_kcal_mol"], 0.525, atol=1e-12)


def test_corrected_interactions_and_dummy_filter():
    interactions = fd.table("interactions")
    bio39 = interactions.query("PDB_ID == '4Z45' and bio_id == 'Bio39'")
    distances = {(row.receptor_atom, row.ligand_atom): row.minimum_strict_heavy_atom_distance_A for row in bio39.itertuples()}
    assert np.isclose(distances[("N", "O")], 2.905, atol=1e-12)
    assert np.isclose(distances[("CB", "O")], 3.591, atol=1e-12)
    representative = fd.representative_complexes().query("bio_id == 'Bio38'").iloc[0]
    text = fd.filtered_pose_text(representative["representative_pose_path"], "Bio38")
    atom_names = [line[12:16].strip() for line in text.splitlines() if line.startswith(("ATOM", "HETATM"))]
    assert "G0" not in atom_names


