def _open_app(page: str):
    app = AppTest.from_file(str(ROOT / "app.py"), default_timeout=90)
    app.run()
    app.radio[0].set_value(page).run()
    assert not app.exception, [str(item.value) for item in app.exception]
    return app


def test_all_existing_top_level_routes():
    routes = [
        "Dashboard", "Published GC-MS Features", "Chemical Structure Explorer",
        "Biological & Sample Contexts", "Published Feature Statistics", "Evidence Explorer",
        "Docking Predictions", "Feature-Context Network", "Structural Similarity Explorer",
        "References / Data Sources", "Research Team Assistant",
    ]
    for route in routes:
        _open_app(route)


def test_all_docking_subviews():
    app = _open_app("Docking Predictions")
    for view in [
        "Overview", "Receptor × VOC matrix", "VOC explorer", "Receptor comparison",
        "Seed variability", "Pose explorer", "Docking validation", "Methods & provenance",
    ]:
        app.selectbox[0].set_value(view).run()
        assert not app.exception, (view, [str(item.value) for item in app.exception])


